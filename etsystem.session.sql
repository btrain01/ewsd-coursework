--Enum Types
CREATE TYPE meeting_status AS ENUM (
  'SCHEDULED',
  'CONFIRMED',
  'IN_PROGRESS',
  'COMPLETED',
  'CANCELLED'
);

CREATE TYPE meeting_type AS ENUM (
  'PHYSICAL',
  'VIRTUAL'
);

CREATE TYPE notification_type AS ENUM (
  'MESSAGE',
  'EMAIL'
);

CREATE TYPE audit_log_action_types AS ENUM (
  'INSERT',
  'UPDATE',
  'DELETE',
  'FETCH'
);

--Core System Tables

CREATE TABLE roles (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(50)  UNIQUE NOT NULL,
  description VARCHAR(255),
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE  roles      IS 'System user roles';
COMMENT ON COLUMN roles.name IS 'Role name: admin, staff, tutor, student';

CREATE TABLE permissions (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resource    VARCHAR(100) UNIQUE NOT NULL,
  description VARCHAR(255),
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE permissions IS 'System permissions for role-based access control';

CREATE TABLE users (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(50)  UNIQUE NOT NULL,
  email         VARCHAR(254) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  first_name    VARCHAR(150) NOT NULL,
  last_name     VARCHAR(150) NOT NULL,
  role_id       INT,
  is_logged_in  BOOLEAN  NOT NULL DEFAULT TRUE,
  last_login_at TIMESTAMPTZ,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE users IS 'System users with role-based access';
COMMENT ON COLUMN users.last_login_at IS 'Track last login time for security monitoring';

CREATE TABLE role_permissions (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id       INT         NOT NULL,
  permission_id INT         NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE tutor_assignments (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tutor_id     INT         NOT NULL,
  student_id   INT         NOT NULL,
  allocated_by INT         NOT NULL,
  notes        TEXT,
  deleted_at   TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE tutor_assignments IS 'Tutor-student allocations with complete history';
COMMENT ON COLUMN tutor_assignments.deleted_at IS 'Soft delete for allocation history';

CREATE TABLE messages (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id    INT         NOT NULL,
  recipient_id INT         NOT NULL,
  subject      VARCHAR(200),
  body         TEXT        NOT NULL,
  is_read      BOOLEAN     NOT NULL DEFAULT false,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE messages IS 'User-to-user messages within tutoring context';

CREATE TABLE meetings (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organiser_id INT NOT NULL,
  title VARCHAR(140) NOT NULL,
  description TEXT,
  meeting_status meeting_status NOT NULL,
  meeting_type meeting_type NOT NULL,
  scheduled_at TIMESTAMPTZ NOT NULL,
  duration_minutes INTEGER NOT NULL DEFAULT 60,
  location_or_url VARCHAR(500),
  cancellation_reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE meeting_participants (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meeting_id INT NOT NULL,
  user_id    INT NOT NULL,
  role       VARCHAR(20) CHECK (role IN ('organizer', 'tutor', 'student')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT unique_meeting_participant UNIQUE (meeting_id, user_id)
);

COMMENT ON TABLE meeting_participants IS 'Meeting participants with their roles';

CREATE TABLE meeting_feedback (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meeting_id INT NOT NULL,
  user_id    INT NOT NULL,
  rating     INT CHECK (rating BETWEEN 1 AND 5),
  comments   TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT unique_meeting_feedback UNIQUE (meeting_id, user_id)
);

COMMENT ON TABLE meeting_feedback IS 'Feedback and ratings for completed meetings';

COMMENT ON TABLE  meetings                  IS 'Scheduled tutoring sessions';
COMMENT ON COLUMN meetings.duration_minutes IS 'Between 15 and 480';

CREATE TABLE documents (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uploader_id INT NOT NULL,
  meeting_id INT NOT NULL,
  filename VARCHAR(255) NOT NULL,
  mime_path VARCHAR(500) NOT NULL,
  file_size BIGINT NOT NULL,
  description VARCHAR(200),
  content TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE documents IS 'Shared documents and resources for tutoring sessions';

CREATE TABLE document_comments (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id INT         NOT NULL,
  author_id   INT         NOT NULL,
  body        TEXT        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE document_comments IS 'Comments on shared documents';

CREATE TABLE blog_posts (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id  INT          NOT NULL,
  title      VARCHAR(300) NOT NULL,
  body       TEXT         NOT NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE blog_posts IS 'Knowledge base articles and announcements';

CREATE TABLE blog_comments (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id    INT         NOT NULL,
  author_id  INT         NOT NULL,
  body       TEXT        NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE blog_comments IS 'Comments on blog posts';

CREATE TABLE notifications (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INT               NOT NULL,
  type       notification_type NOT NULL,
  title      VARCHAR(200)      NOT NULL,
  message    TEXT              NOT NULL,
  created_at TIMESTAMPTZ       NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ       NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE notifications IS 'User notifications for system events';

CREATE TABLE audit_logs (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name VARCHAR(50)             NOT NULL,
  record_id  INT                     NOT NULL,
  action     audit_log_action_types  NOT NULL,
  old_data   JSONB,
  new_data   JSONB,
  changed_by INT,
  created_at TIMESTAMPTZ             NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ             NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE audit_logs IS 'Comprehensive audit trail for compliance';

